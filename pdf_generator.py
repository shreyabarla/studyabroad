from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch

styles = getSampleStyleSheet()


def generate_pdf(filepath, country, reasons, universities, course):

    doc = SimpleDocTemplate(filepath, rightMargin=35,
                            leftMargin=35, topMargin=40)

    story = []

    # ---------- TITLE ----------
    title = Paragraph(
        "<font size=20 color='#1F4F82'><b>Study Abroad Recommendation Report</b></font>",
        styles["Title"]
    )

    story.append(title)
    story.append(Spacer(1, 0.25*inch))

    # ---------- RECOMMENDED COUNTRY ----------
    story.append(
        Paragraph(
            "<font size=14><b>Recommended Country</b></font>",
            styles["Heading2"]
        )
    )

    country_table = Table([[country]], colWidths=[5.8*inch])

    country_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#E8F5E9")),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#2E7D32")),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 16),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 12),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.white)
    ]))

    story.append(country_table)
    story.append(Spacer(1, 0.25*inch))

    # ---------- REASONS ----------
    story.append(
        Paragraph(
            "<font size=14><b>Why this country?</b></font>",
            styles["Heading2"]
        )
    )

    for reason in reasons:
        story.append(Paragraph(f"• {reason}", styles["BodyText"]))

    story.append(Spacer(1, 0.25*inch))

    # ---------- UNIVERSITIES ----------
    story.append(
        Paragraph(
            "<font size=14><b>Top Universities</b></font>",
            styles["Heading2"]
        )
    )

    uni_data = [["University", "City", "QS Rank", "IELTS"]]

    for u in universities:
        uni_data.append([
            u[1],
            u[2],
            str(u[3]),
            str(u[5])
        ])

    uni_table = Table(
        uni_data,
        colWidths=[2.7*inch, 1.3*inch, 0.9*inch, 0.9*inch]
    )

    uni_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F4F82")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("BACKGROUND", (0, 1), (-1, -1), colors.whitesmoke),
        ("ALIGN", (2, 1), (-1, -1), "CENTER"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 8)
    ]))

    story.append(uni_table)
    story.append(Spacer(1, 0.3*inch))

    # ---------- COURSE ----------
    if course:

        story.append(
            Paragraph(
                "<font size=14><b>Recommended Course</b></font>",
                styles["Heading2"]
            )
        )

        course_table = Table([
            ["Course", course[0]],
            ["Degree", course[1]],
            ["Duration", course[2]],
            ["Tuition Fee", f"₹ {course[3]:,}"]
        ], colWidths=[1.8*inch, 4.0*inch])

        course_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E3F2FD")),
            ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#0D47A1")),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 8)
        ]))

        story.append(course_table)

    else:

        story.append(
            Paragraph(
                "<b>Recommended Course</b><br/>No suitable course found.",
                styles["BodyText"]
            )
        )

    story.append(Spacer(1, 0.35*inch))

    # ---------- FOOTER ----------
    footer = Paragraph(
        "<font size=9 color='grey'>Generated by Study Abroad Recommendation System | Flask + PostgreSQL</font>",
        styles["Normal"]
    )

    story.append(footer)

    doc.build(story)